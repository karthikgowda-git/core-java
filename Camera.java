public class Camera {

    public static void initializeCamera() {
        System.out.println("Camera initialized successfully.");
    }

    public static void powerOnCamera() {
        System.out.println("Camera powered on.");
    }

    public static void configureResolution() {
        System.out.println("Camera resolution configured.");
    }

    public static void adjustBrightness() {
        System.out.println("Brightness adjusted.");
    }

    public static void adjustContrast() {
        System.out.println("Contrast adjusted.");
    }

    public static void enableFlash() {
        System.out.println("Flash enabled.");
    }

    public static void disableFlash() {
        System.out.println("Flash disabled.");
    }

    public static void setFocusMode() {
        System.out.println("Focus mode selected.");
    }

    public static void capturePhoto() {
        System.out.println("Photo captured successfully.");
    }

    public static void recordVideo() {
        System.out.println("Video recording started.");
    }

    public static void stopVideoRecording() {
        System.out.println("Video recording stopped.");
    }

    public static void savePhoto() {
        System.out.println("Photo saved to memory.");
    }

    public static void deletePhoto() {
        System.out.println("Photo deleted.");
    }

    public static void viewGallery() {
        System.out.println("Gallery opened.");
    }

    public static void zoomIn() {
        System.out.println("Camera zoomed in.");
    }

    public static void zoomOut() {
        System.out.println("Camera zoomed out.");
    }

    public static void switchToFrontCamera() {
        System.out.println("Front camera activated.");
    }

    public static void switchToRearCamera() {
        System.out.println("Rear camera activated.");
    }

    public static void enableNightMode() {
        System.out.println("Night mode enabled.");
    }

    public static void enablePortraitMode() {
        System.out.println("Portrait mode enabled.");
    }

    public static void applyFilter() {
        System.out.println("Camera filter applied.");
    }

    public static void scanQRCode() {
        System.out.println("QR code scanned successfully.");
    }

    public static void detectFace() {
        System.out.println("Face detected.");
    }

    public static void stabilizeImage() {
        System.out.println("Image stabilization enabled.");
    }

    public static void checkBatteryStatus() {
        System.out.println("Camera battery status checked.");
    }

    public static void connectToWifi() {
        System.out.println("Camera connected to Wi-Fi.");
    }

    public static void updateFirmware() {
        System.out.println("Camera firmware updated.");
    }

    public static void powerOffCamera() {
        System.out.println("Camera powered off.");
    }

    public static void main(String[] args) {

        initializeCamera();
        powerOnCamera();
        configureResolution();
        adjustBrightness();
        adjustContrast();
        enableFlash();
        disableFlash();
        setFocusMode();
        capturePhoto();
        recordVideo();
        stopVideoRecording();
        savePhoto();
        deletePhoto();
        viewGallery();
        zoomIn();
        zoomOut();
        switchToFrontCamera();
        switchToRearCamera();
        enableNightMode();
        enablePortraitMode();
        applyFilter();
        scanQRCode();
        detectFace();
        stabilizeImage();
        checkBatteryStatus();
        connectToWifi();
        updateFirmware();
        powerOffCamera();
    }
}